// Junta a base com os textos de um idioma (indexados por slug)
export function comTextos(textos: Record<string, FeaturedProjectText>): FeaturedProject[] {
  return projetosBase.map((projeto) => {
    const texto = textos[projeto.slug];
    if (!texto) throw new Error(`Textos ausentes para o projeto "${projeto.slug}"`);
    return { ...projeto, ...texto };
  });
}
